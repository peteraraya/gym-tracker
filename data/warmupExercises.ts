export const getWarmupsByMuscleGroup = (muscleGroup: MuscleGroup): WarmupExercise[] => {
  return WARMUP_DATABASE
    .filter(ex => ex.muscleGroup === muscleGroup || ex.targetMuscles.includes(muscleGroup))
    .sort((a, b) => a.priority - b.priority);
};

// Obtener todos los ejercicios de calentamiento
export const getAllWarmups = (): WarmupExercise[] => {
  return WARMUP_DATABASE;
};

// Obtener ejercicios de calentamiento por categoría
export const getWarmupsByCategory = (category: WarmupCategory): WarmupExercise[] => {
  return WARMUP_DATABASE.filter(ex => ex.category === category);
};

// Obtener calentamiento recomendado para una rutina basado en los grupos musculares
export const getRecommendedWarmups = (muscleGroups: MuscleGroup[]): WarmupExercise[] => {
  const uniqueMuscles = [...new Set(muscleGroups)];
  const warmups = new Map<string, WarmupExercise>();

  uniqueMuscles.forEach(muscle => {
    const muscleWarmups = getWarmupsByMuscleGroup(muscle);
    muscleWarmups.forEach(warmup => {
      if (!warmups.has(warmup.id)) {
        warmups.set(warmup.id, warmup);
      }
    });
  });

  return Array.from(warmups.values()).sort((a, b) => {
    // Primero por prioridad, luego por categoría
    if (a.priority !== b.priority) return a.priority - b.priority;
    const categoryOrder: Record<WarmupCategory, number> = { warmup: 0, mobility: 1, activation: 2 };
    return categoryOrder[a.category] - categoryOrder[b.category];
  });
};

